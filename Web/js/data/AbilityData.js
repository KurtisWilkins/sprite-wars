// -- Helper Functions --

/**
 * Returns the ability object for a given ID, or null if not found.
 * @param {number} id
 * @returns {Ability|null}
 */
export function getAbility(id) {
	return ABILITIES[id] || null;
}

/**
 * Returns an array of all abilities matching the given element type.
 * @param {string} element - e.g. "Fire", "Water", "Dark"
 * @returns {Ability[]}
 */
export function getAbilitiesByElement(element) {
	return Object.values(ABILITIES).filter(a => a.element_type === element);
}

/**
 * Returns an array of all abilities matching the given class affinity.
 * @param {string} className - e.g. "Paladin", "Fighter", "Barbarian", "Any"
 * @returns {Ability[]}
 */
export function getAbilitiesByClass(className) {
	return Object.values(ABILITIES).filter(a => a.class_affinity === className);
}
